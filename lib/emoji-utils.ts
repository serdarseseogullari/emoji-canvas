// Merge and deduplicate all emojis for shuffle mode
const allColorEmojis = Object.values(colorCategories).flat()
const allEmojiSet = Array.from(new Set([...allColorEmojis, ...shuffleExtras]))

// Get a random emoji, optionally filtered by color
export function getRandomEmoji(color?: string): string {
  if (color && colorCategories[color]) {
    const colorEmojis = colorCategories[color]
    return colorEmojis[Math.floor(Math.random() * colorEmojis.length)]
  }
  return allEmojiSet[Math.floor(Math.random() * allEmojiSet.length)]
}

